def generate_rust_header(component_name: str, registers: list[dict]) -> str:
    struct_name = "".join(w.capitalize() for w in component_name.split("_"))

    lines = [
        "// -------------------------------------------------------------------------- ",
        f"// Component : {component_name} - Register Map",
        "// Auto-generated by sphinx-rtl                                               ",
        "// -------------------------------------------------------------------------- ",
        "#[derive(Copy, Clone, Debug, PartialEq, Eq)]",
        "#[repr(C, packed)]",
        f"pub struct {struct_name}Regs {{",
    ]

    longest = max([len(f["name"]) for f in registers])

    for f in registers:
        if f["is_padding"]:
            lines.append(f"    pub {f['name']}: [u8; {f['size_bytes']}],")
        else:
            rust_type = (
                "u32"
                if f["size_bytes"] >= 4
                else ("u16" if f["size_bytes"] == 2 else "u8")
            )
            lines.append(
                f"    pub {f['name']}: {rust_type},{" "*(longest + 4 - len(f["name"]))}// Offset: 0x{f['offset']:02X}"
            )

    lines.append("}")
    return "\n".join(lines)
