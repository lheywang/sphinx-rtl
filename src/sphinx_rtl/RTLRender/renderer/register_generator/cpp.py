def generate_c_header(component_name: str, registers: list[dict]) -> str:
    """
    Generate a C/C++ template ready to be included into a build.
    """

    guard_name = f"REGISTERS_{component_name.upper()}_H"

    lines = [
        "/* -------------------------------------------------------------------------- */",
        f"/* Component : {component_name} - Register Map{" " * (48 - len(component_name))}*/",
        "/* Auto-generated by sphinx-rtl                                               */",
        "/* -------------------------------------------------------------------------- */",
        f"#ifndef {guard_name}",
        f"#define {guard_name}",
        "",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "#pragma pack(push, 1)",
        f"typedef struct {{",
    ]

    longest = max([len(f["name"]) for f in registers])

    for f in registers:
        if f["is_padding"]:
            lines.append(f"    uint8_t {f['name']}[{f['size_bytes']}];")
        else:
            c_type = (
                "uint32_t"
                if f["size_bytes"] >= 4
                else ("uint16_t" if f["size_bytes"] == 2 else "uint8_t")
            )
            lines.append(
                f"    {c_type} {f['name']};{" "*(longest + 4 - len(f["name"]))}/* Offset: 0x{f['offset']:02X} */"
            )

    lines.extend(
        [
            f"}} {component_name.lower()}_regs_t;",
            "",
            "#pragma pack(pop)",
            "",
            "#ifdef __cplusplus",
            "}",
            "#endif",
            "",
            f"#endif /* {guard_name} */",
            "",
        ]
    )

    return "\n".join(lines)
